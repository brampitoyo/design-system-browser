const HEX_RE = /^#[0-9a-fA-F]{6}$/;

function validatePalettes(): void {
  for (const [name, palette] of Object.entries(palettes)) {
    if (!palette.colors || typeof palette.colors !== 'object') {
      console.warn(`[palettes] ${name}: missing or invalid colors`);
    }
    if (!palette.spacing || typeof palette.spacing !== 'object') {
      console.warn(`[palettes] ${name}: missing or invalid spacing`);
    }
    if (!palette.typography || typeof palette.typography !== 'object') {
      console.warn(`[palettes] ${name}: missing or invalid typography`);
    }

    if (palette.semantic) {
      for (const [key, token] of Object.entries(palette.semantic)) {
        if (!token.light || !token.dark) {
          console.warn(`[palettes] ${name}.semantic.${key}: missing light or dark value`);
        }
        if (token.light && !HEX_RE.test(token.light)) {
          console.warn(`[palettes] ${name}.semantic.${key}.light: invalid hex ${token.light}`);
        }
        if (token.dark && !HEX_RE.test(token.dark)) {
          console.warn(`[palettes] ${name}.semantic.${key}.dark: invalid hex ${token.dark}`);
        }
      }
    }

    if (palette.theme && palette.semantic) {
      for (const [cssVar, tokenName] of Object.entries(palette.theme)) {
        if (!palette.semantic![tokenName]) {
          console.warn(`[palettes] ${name}.theme.${cssVar}: references missing semantic token ${tokenName}`);
        }
      }
    }

    for (const [family, shades] of Object.entries(palette.colors)) {
      for (const [shade, value] of Object.entries(shades)) {
        if (!HEX_RE.test(value)) {
          console.warn(`[palettes] ${name}.colors.${family}.${shade}: invalid hex ${value}`);
        }
      }
    }
  }
}

validatePalettes();
